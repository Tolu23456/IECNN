"""Byte-level decoding from a trained arm (inference only).

This lives in `models/` rather than in a script because three callers need it:
`scripts/sample_compare.py` and `scripts/flavour_probe.py` each grew a private
copy, and the long-budget harness now has to report what the model *says*, not
only its bpc. One implementation means the sampling temperature, top-k and
prompt handling cannot drift between a probe and a training run.

The decode is deliberately cache-free: the model is re-run on the last `ctx`
bytes for every generated byte. A KV cache would be a second code path that
the trained weights have never been checked against, and one short sample per
arm does not justify that risk.
"""
from __future__ import annotations

import torch
import torch.nn.functional as F


@torch.no_grad()
def generate_bytes(model, prompt: torch.Tensor, n: int, mode: str = "sample",
                   temp: float = 0.7, topk: int = 40, ctx: int = 256,
                   seed: int = 1234) -> bytes:
    """Decode `n` bytes from a [1, p] prompt.

    mode="greedy" takes the argmax at every step; anything else samples from
    top-k with temperature `temp`. `ctx` is the model's context window: the
    prompt is truncated to its last `ctx` bytes, so generation is valid for
    prompts longer than the trained context (it is not trained that way, and
    the harness always passes p <= ctx).

    The return is `bytes`, so the model's vocab must be <= 256 (the corpus is
    byte-level, V=256); a larger vocab raises from `bytes()` rather than
    silently truncating.
    """
    if prompt.dim() != 2 or prompt.shape[0] != 1:
        raise ValueError(f"prompt must be [1, p], got {tuple(prompt.shape)}")
    if n < 0:
        raise ValueError("n must be >= 0")
    model.eval()
    dev = prompt.device
    # The generator lives on CPU unconditionally: torch.Generator(device="xla")
    # does not exist, and one extra 256-float transfer per byte is nothing next
    # to a forward pass. One code path for cuda, xla and cpu beats a branch
    # that can silently sample differently per backend.
    g = torch.Generator().manual_seed(int(seed))
    seq = prompt.clone()
    out = bytearray()
    for _ in range(int(n)):
        lp = model(seq[:, -int(ctx):])["final_log_probs"][:, -1]   # [1, V]
        if mode == "greedy":
            nxt = lp.argmax(-1)
        else:
            logits = lp / max(float(temp), 1e-6)
            if 0 < int(topk) < logits.shape[-1]:
                th = torch.topk(logits, int(topk), dim=-1).values[:, -1:]
                logits = logits.masked_fill(logits < th, float("-inf"))
            prob = F.softmax(logits, dim=-1)
            nxt = torch.multinomial(prob.cpu(), 1, generator=g).to(dev)
        out.append(int(nxt.reshape(-1)[0].item()))
        seq = torch.cat([seq, nxt.reshape(1, 1)], dim=1)
    return bytes(out)
